/** Odmiana „strona” dla liczby (polski) / „page(s)” (angielski). */
fun pagesWord(n: Int): String {
    if (I18n.english) return if (n == 1) "$n page" else "$n pages"
    val m10 = n % 10
    val m100 = n % 100
    val w = when {
        n == 1 -> "stronę"
        m10 in 2..4 && m100 !in 12..14 -> "strony"
        else -> "stron"
    }
    return "$n $w"
}
